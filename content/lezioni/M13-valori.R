RNGkind("Mersenne-Twister", "Inversion", "Rejection")
setwd("lezioni/M13_Strata")
v <- function(nome, x) cat(sprintf("%-38s %s\n", nome, paste(format(x, digits = 7), collapse = "  ")))
cr <- read.csv("dati/cronologia_v3.csv"); px <- read.csv("dati/proxy_v3.csv")
z <- cr$profondita_cm; t <- cr$eta_cal_BP
v("base ancore z", z); v("base ancore t", t); v("base sd", cr$sd_scenario_anni)
v("base proxy n, passo, range z, range proxy", c(nrow(px), diff(px$profondita_cm)[1], range(px$profondita_cm), range(px$proxy)))
v("base proxy max: profondita", px$profondita_cm[which.max(px$proxy)])
tp <- approx(z, t, px$profondita_cm)$y
v("base eta al massimo", tp[which.max(px$proxy)])
v("4 durate segmenti", diff(t)); v("4 spessori", diff(z))
v("4 tassi cm/anno, anni/cm", c(diff(z) / diff(t), diff(t) / diff(z)))
v("11-12 anno astronomico 900, 1300", c(1950 - 900, 1950 - 1300))
v("11 tassi esperimento 80: anni/cm prima e dopo (900)", c((900 - 350) / 40, (1700 - 900) / 40))
v("12 tassi con 1300", c((1300 - 350) / 40, (1700 - 1300) / 40))
v("13 eta a 35", approx(c(20, 50), c(160, 450), xout = 35)$y)
v("15 eta a 100", approx(z, t, xout = 100)$y)
v("16 tassi mm/anno", 10 * diff(z) / diff(t))
v("7 anni astronomici 160, 2200", c(1950 - 160, 1950 - 2200))
r <- diff(z) / diff(t)
v("17-19 media semplice, ponderata, totale cm/anno", c(mean(r), sum(diff(t) * r) / sum(diff(t)), 160 / 2200))
v("17 totale mm/anno", 1600 / 2200)
v("22 sd con rho 0, 0.6", sqrt((25^2 + 40^2 + 2 * c(0, .6) * 25 * 40) / 4))
u <- read.csv("dati/casuali_comuni_v3.csv")
E <- matrix(u$z[1:3000], 500, 6, byrow = TRUE); A <- sweep(E, 2, cr$sd_scenario_anni, "*"); A <- sweep(A, 2, t, "+")
v("24 accettati, distanza minima fra ancore consecutive", c(sum(apply(A, 1, function(a) all(diff(a) > 0))), min(apply(A, 1, function(a) min(diff(a))))))
a100 <- apply(A, 1, function(a) approx(z, a, xout = 100)$y)
v("26-29 quantili eta a 100", quantile(a100, c(.025, .5, .975)))
v("26 sd eta a 100 MC e teorica", c(sd(a100), sqrt((55^2 + 80^2) / 4)))
v("32 anni per 2 cm, tutti i segmenti", 2 * diff(t) / diff(z))
v("33 proxy: n, min, max, profondita del minimo", c(nrow(px), range(px$proxy), px$profondita_cm[which.min(px$proxy)]))
dtp <- diff(tp)
v("34-35 intervalli fra campioni: min, max, valori distinti", c(min(dtp), max(dtp), sort(unique(round(dtp, 2)))))
v("34 eta dei campioni: prima e ultima", range(tp))
i <- 20; w <- abs(tp - tp[i]) <= 100
v("36-38 campione centrale: profondita, eta", c(px$profondita_cm[i], tp[i]))
v("36 finestra 5 punti: profondita estreme, durata", c(px$profondita_cm[c(i - 2, i + 2)], tp[i + 2] - tp[i - 2]))
v("38 finestra 100 anni: n, profondita estreme", c(sum(w), range(px$profondita_cm[w])))
v("38 medie 5 punti, 100 anni", c(mean(px$proxy[(i - 2):(i + 2)]), mean(px$proxy[w])))
v("38 tabella N11", read.csv("Tabelle/M13_N11.csv")$media)
v("37 righe griglia a 10 anni", length(seq(0, 2200, 10)))
ze <- c(0, 40, 80, 120, 160); te <- c(0, 350, 900, 1700, 2200)
for (s in c(5, 15)) { d5 <- seq(0, 160, s); a5 <- approx(ze, te, d5)$y
  v(paste("39-40 passo", s, ": n, ultima profondita, min, max intervallo"), c(length(d5), max(d5), min(diff(a5)), max(diff(a5)))) }
v("41 limite superiore e inferiore", c(t[z == 80], t[z == 80] + 400))
v("42 eta base 120 e 160, con hiatus", c(t[z == 120], t[z == 160], t[z %in% c(120, 160)] + 400))
tb <- t; tb[4] <- 300; j <- which(diff(tb) <= 0)
v("43-46 inversione: da, a, delta, numero segmenti", c(z[j], z[j + 1], diff(tb)[j], length(j)))
fit <- lm(t ~ z)
v("44 retta: intercetta, pendenza anni/cm", coef(fit))
v("44 residui alle ancore", residuals(fit))
v("44 eta retta a 0 e 160", predict(fit, data.frame(z = c(0, 160))))
ii <- 2:5; q <- sapply(ii, function(k) approx(z[-k], t[-k], xout = z[k])$y)
v("45-47 previste senza ancora", q); v("45-47 errori previsto-osservato", q - t[ii])
e50 <- approx(z, t, xout = c(60, 100))$y
v("50 eta 60 e 100, durata", c(e50, diff(e50)))
w60 <- c(2/3, 1/3, 0); w100 <- c(0, 1/2, 1/2); s3 <- cr$sd_scenario_anni[3:5]
v("52 pesi D su ancore 50, 80, 120", w100 - w60)
v("52 sd T60, T100, cov, sd D", c(sqrt(sum((w60 * s3)^2)), sqrt(sum((w100 * s3)^2)), sum(w60 * w100 * s3^2), sqrt(sum(((w100 - w60) * s3)^2))))
v("52 sd D se indipendenti", sqrt(sum((w60 * s3)^2) + sum((w100 * s3)^2)))
he <- function(H) approx(ze, te, 120)$y + H
v("48-49 eta a 120 con hiatus 400 e 800 (esperimento)", c(he(400), he(800)))
dur <- apply(A, 1, function(a) diff(approx(z, a, xout = c(60, 100))$y))
v("53-56 durate: n, quantili", c(length(dur), quantile(dur, c(.025, .5, .975))))
v("53-54 durate: sd MC, sd analitica, distanze dei quantili dalla mediana", c(sd(dur), 48.94016, quantile(dur, .5) - quantile(dur, .025), quantile(dur, .975) - quantile(dur, .5)))
v("55 massimo: profondita, proxy, eta base, eta hiatus", c(px$profondita_cm[which.max(px$proxy)], max(px$proxy), tp[which.max(px$proxy)], tp[which.max(px$proxy)] + 400))
v("55 secondo valore piu alto e sua profondita", c(sort(px$proxy, TRUE)[2], px$profondita_cm[order(-px$proxy)[2]]))
for (rho in c(.6, -.6)) { set.seed(17); uu <- rnorm(200); vv <- rho * uu + sqrt(1 - rho^2) * rnorm(200)
  dd <- (1000 + 100 * vv) - (500 + 80 * uu)
  v(paste("57-58 rho", rho, ": sd sim, sd analitica, media"), c(sd(dd), sqrt(80^2 + 100^2 - 2 * rho * 80 * 100), mean(dd))) }
v("55 proxy a 156, 158, 160 cm", px$proxy[px$profondita_cm %in% c(156, 158, 160)])
v("54 contributi alla varianza della durata: ancore 50, 80, 120", ((w100 - w60) * s3)^2)
