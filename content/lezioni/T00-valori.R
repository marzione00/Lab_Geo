RNGkind("Mersenne-Twister", "Inversion", "Rejection")
setwd("lezioni/T00_Basalto")
v <- function(nome, x) cat(sprintf("%-38s %s\n", nome, paste(format(x, digits = 7), collapse = "  ")))
cm <- read.csv("dati/campioni_modulo1.csv")
cm$rho <- cm$massa_g / cm$volume_cm3
v("base n, stazioni, affioramenti", c(nrow(cm), length(unique(cm$stazione)), length(unique(cm$affioramento))))
v("base per stazione", table(cm$stazione))
v("base range massa, volume, rho", c(range(cm$massa_g), range(cm$volume_cm3), range(cm$rho)))
v("base media rho per affioramento", tapply(cm$rho, cm$affioramento, mean))
v("base alterazione", table(cm$alterazione))
v("4 rho C01-C03", round(cm$rho[1:3], 4))
v("10 media x, media y (a=1000, 100)", c(mean(c(0.12, 0.18, 0.21, 0.16, 0.24, 0.19)), 1000 * mean(c(0.12, 0.18, 0.21, 0.16, 0.24, 0.19)), 100 * mean(c(0.12, 0.18, 0.21, 0.16, 0.24, 0.19))))
xs <- c(2, 7, 4, 9, 1, 6, 3, 8, 5, 10)
v("18-19 selezionati e media >5, >7", c(sum(xs > 5), mean(xs[xs > 5]), sum(xs > 7), mean(xs[xs > 7])))
v("19 media con >= 5", mean(xs[xs >= 5]))
v("20 media con NA come zero", mean(c(40, 0, 50)))
v("12 masse > 120 nel registro", sum(cm$massa_g > 120))
v("27 media rho, rapporto somme", c(mean(cm$rho), sum(cm$massa_g) / sum(cm$volume_cm3)))
v("26 media rho per stazione", tapply(cm$rho, cm$stazione, mean))
v("26 sd rho entro stazioni media, sd medie stazione", c(mean(tapply(cm$rho, cm$stazione, sd)), sd(tapply(cm$rho, cm$stazione, mean))))
v("24 provini con V >= 45", sum(cm$volume_cm3 >= 45))
v("35-36 media 5 valori, media senza il 12", c(mean(c(3, 4, 5, 6, 12)), mean(c(3, 4, 5, 6))))
v("37 2.68 g/cm3 in kg/m3", 2.68 * 1000)
v("43-44 scarto massimo hidden 2, 6", c(max(abs(1:6 * 2 - 1:6 * 3)), max(abs(1:6 * 6 - 1:6 * 3))))
v("45 sd n-1, sd n", c(sd(1:3), sqrt(mean((1:3 - 2)^2))))
v("50 MB matrice 1e6 x 100 double", 8 * 1e6 * 100 / 1e6)
set.seed(17); x57 <- runif(30)
e2 <- x57 - round(x57, 2); e0 <- x57 - round(x57, 0)
v("57-58 errore max, MSE con 2 e 0 cifre", c(max(abs(e2)), mean(e2^2), max(abs(e0)), mean(e0^2)))
v("57 limiti teorici max errore 2, 0 cifre; var uniforme", c(0.005, 0.5, 0.01^2 / 12, 1 / 12))
v("59 scarto max con 1 cifra", max(abs(c(2.68, 2.71, 2.65) - round(c(2.68, 2.71, 2.65), 1))))
v("63 (1e16+1)-1e16, (1e10+1)-1e10, eps", c((1e16 + 1) - 1e16, (1e10 + 1) - 1e10, .Machine$double.eps, 2^53))
