library(sf)
print(packageVersion("sf"));print(sf_extSoftVersion())
d<-read.csv("Dati/spazio_v3.csv")
p<-st_as_sf(d,coords=c("lon","lat"),crs="OGC:CRS84",remove=FALSE)
q<-st_transform(p,32632)
b<-st_coordinates(st_transform(q,"OGC:CRS84"))
print(head(st_coordinates(q)))
print(max(abs(b-as.matrix(d[c("lon","lat")]))))
st_write(p,"Verifiche/test_sf_runtime.geojson",driver="GeoJSON",delete_dsn=TRUE,quiet=TRUE,layer_options=c("RFC7946=YES","COORDINATE_PRECISION=10"))
p1<-st_read("Verifiche/test_sf_runtime.geojson",quiet=TRUE)
stopifnot(nrow(p1)==64,setequal(p1$id,d$id),max(abs(b-as.matrix(d[c("lon","lat")])))<1e-7)
writeLines(capture.output(sessionInfo()),"Verifiche/SESSIONE_SF_RUNTIME.txt")
cat("sf: trasformazione e GeoJSON eseguiti.\n")
